// Regenerate with: node scripts/generate-width-data.mjs /path/to/unicode-17-data
// Download the four source files from the URLs recorded below into that directory.
// This script is a development utility; the application never fetches Unicode data.
import { readFile, writeFile } from 'node:fs/promises';
import { createHash } from 'node:crypto';
import { resolve } from 'node:path';

const directory = process.argv[2];
if (!directory) throw new Error('Pass a directory containing the Unicode 17.0 source files.');
const base = 'https://www.unicode.org/Public/17.0.0/ucd/';
const sources = {
  'EastAsianWidth.txt': `${base}EastAsianWidth.txt`,
  'DerivedGeneralCategory.txt': `${base}extracted/DerivedGeneralCategory.txt`,
  'emoji-data.txt': `${base}emoji/emoji-data.txt`,
  'emoji-variation-sequences.txt': `${base}emoji/emoji-variation-sequences.txt`,
};
const text = {}, provenance = {};
for (const [file, url] of Object.entries(sources)) {
  const bytes = await readFile(resolve(directory, file));
  text[file] = bytes.toString('utf8');
  provenance[file] = { url, sha256: createHash('sha256').update(bytes).digest('hex') };
}
if (!text['EastAsianWidth.txt'].includes('EastAsianWidth-17.0.0.txt')
  || !text['DerivedGeneralCategory.txt'].includes('DerivedGeneralCategory-17.0.0.txt')
  || !text['emoji-data.txt'].includes('# Version: 17.0')
  || !text['emoji-variation-sequences.txt'].includes('# Version: 17.0')) {
  throw new Error('Expected Unicode 17.0 data; do not silently mix Unicode versions.');
}
function merge(ranges) {
  const result = [];
  for (const [start, end] of ranges.sort((a, b) => a[0] - b[0])) {
    const last = result.at(-1);
    if (last && start <= last[1] + 1) last[1] = Math.max(last[1], end);
    else result.push([start, end]);
  }
  return result.flat();
}
function ranges(file, properties) {
  const result = [];
  for (const line of text[file].split('\n')) {
    const match = line.match(/^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*(\w+)/);
    if (match && properties.includes(match[3])) result.push([parseInt(match[1], 16), parseInt(match[2] || match[1], 16)]);
  }
  return merge(result);
}
const variation = [];
for (const line of text['emoji-variation-sequences.txt'].split('\n')) {
  const match = line.match(/^([0-9A-F]+) FE0F\s*;\s*emoji style/);
  if (match) variation.push([parseInt(match[1], 16), parseInt(match[1], 16)]);
}
const tables = {
  wideRanges: ranges('EastAsianWidth.txt', ['W', 'F']),
  combiningRanges: ranges('DerivedGeneralCategory.txt', ['Mn', 'Mc', 'Me', 'Cf']),
  emojiPresentationRanges: ranges('emoji-data.txt', ['Emoji_Presentation']),
  extendedPictographicRanges: ranges('emoji-data.txt', ['Extended_Pictographic']),
  emojiVariationRanges: merge(variation),
};
let output = '// Generated by scripts/generate-width-data.mjs from Unicode 17.0.0.\n'
  + '// Unicode data copyright © Unicode, Inc.; see UNICODE-LICENSE.txt.\n'
  + '// Do not edit by hand. Ranges are sorted inclusive [start,end] pairs.\n'
  + `export const UNICODE_WIDTH_VERSION = '17.0.0';\n`
  + `export const UNICODE_WIDTH_SOURCES = ${JSON.stringify(provenance, null, 2)};\n`;
for (const [name, table] of Object.entries(tables)) {
  output += `export const ${name} = [\n`;
  for (let i = 0; i < table.length; i += 12) output += `  ${table.slice(i, i + 12).map(n => `0x${n.toString(16)}`).join(', ')},\n`;
  output += '];\n';
}
await writeFile(new URL('../shared/unicode-width-data.js', import.meta.url), output);
